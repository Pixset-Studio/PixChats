-- ============================================================
-- PixChats — Фаза 1: DELETE-политика для chat_members (её не было вообще)
-- ============================================================
-- Обнаружено: ни для self-leave, ни для удаления участника владельцем/админом
-- никогда не было DELETE-политики на chat_members. С включённым RLS это значит,
-- что leaveChat() (выход/отписка) мог тихо ничего не делать — не только сейчас
-- заявленная задача "удалить участника", но и работавшая раньше кнопка "Отписаться"
-- была под тем же риском.

create policy chat_members_delete_self_or_owner on chat_members
  for delete using (
    user_id = auth.uid()
    or is_chat_owner_or_admin(chat_id, auth.uid())
  );
