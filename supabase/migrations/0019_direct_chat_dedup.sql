-- ============================================================
-- PixChats — Фаза 1: жёсткий запрет дублей личных чатов
-- ============================================================
-- Прошлая защита от дублей была только на уровне клиентского кода (поиск
-- существующего чата перед созданием) — при гонке запросов (или просто по
-- сети) могло проскочить два direct-чата между одной и той же парой людей.
-- Теперь это невозможно физически: direct_pair_key — отсортированная пара
-- id участников, уникальный индекс не даст вставить вторую запись.

alter table chats add column direct_pair_key text;
create unique index idx_chats_direct_pair_key on chats (direct_pair_key) where direct_pair_key is not null;
